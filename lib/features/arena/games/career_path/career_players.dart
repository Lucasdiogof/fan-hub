CareerEntry _goias(String period, int? apps, int? goals, {bool loan = false}) =>
    CareerEntry(
      period: period,
      team: 'Goiás',
      appearances: apps,
      goals: goals,
      loan: loan,
      isGoias: true,
    );

CareerEntry _club(
  String period,
  String team,
  int? apps,
  int? goals, {
  bool loan = false,
}) => CareerEntry(
  period: period,
  team: team,
  appearances: apps,
  goals: goals,
  loan: loan,
);

CareerEntry _nat(String period, String team, int? apps, int? goals) =>
    CareerEntry(period: period, team: team, appearances: apps, goals: goals);

CareerAggregateStat _agg(
  String club,
  List<String> spells,
  int? apps,
  int? goals, {
  String? note,
}) => CareerAggregateStat(
  club: club,
  spells: spells,
  appearances: apps,
  goals: goals,
  note: note,
);

